describe("comment view", function()
  local path, store, view, buf, win, original_confirm
  local function press(key)
    local term = vim.api.nvim_replace_termcodes(key, true, false, true)
    for _, map in ipairs(vim.api.nvim_buf_get_keymap(0, "n")) do
      if vim.api.nvim_replace_termcodes(map.lhs, true, false, true) == term then return map.callback() end
    end
    error("missing mapping " .. key)
  end
  local function contents()
    return table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
  end
  local function add(items, fields)
    return (store.insert(items, vim.tbl_extend("force", {
      file = "README.md", line = 5, status = "open", severity = "medium", issue = "First comment",
    }, fields or {})))
  end
  before_each(function()
    path = vim.fn.tempname()
    require("locoreview").setup({ review_file = path, keymaps = false })
    store = require("locoreview.store")
    view = require("locoreview.comment_view")
    vim.cmd("edit README.md")
    original_confirm = require("locoreview.ui").prompt_confirm
    assert.is_true(store.save(path, add(add({}, {}), { issue = "Second comment" })))
  end)
  after_each(function()
    vim.cmd("stopinsert")
    for _, w in ipairs(vim.api.nvim_list_wins()) do
      if vim.api.nvim_win_get_config(w).relative ~= "" then vim.api.nvim_win_close(w, true) end
    end
    require("locoreview.ui").prompt_confirm = original_confirm
    vim.fn.delete(path)
  end)
  it("resolves the selected comment, then reveals and reopens it", function()
    buf, win = view.open(path)
    press("]c")
    press("f")
    local items = store.load(path)
    assert.are.equal("open", items[1].status)
    assert.are.equal("fixed", items[2].status)
    assert.is_nil(contents():find("Second comment", 1, true))
    press("a")
    press("]c")
    press("f")
    assert.are.equal("open", store.load(path)[2].status)
    press("[c")
    press("<C-g>")
    assert.are.equal("high", store.load(path)[1].severity)
    assert.are.equal("medium", store.load(path)[2].severity)
  end)
  it("keeps priority changes on the selected comment", function()
    buf, win = view.open(path)
    press("]c")
    press("<C-g>")
    assert.are.equal("medium", store.load(path)[1].severity)
    assert.are.equal("high", store.load(path)[2].severity)
    assert.matches("RV%-0002", vim.api.nvim_buf_get_lines(buf, vim.api.nvim_win_get_cursor(win)[1] - 1, vim.api.nvim_win_get_cursor(win)[1], false)[1])
  end)
  it("filters source ranges and removed-line comments independently", function()
    local items = add(store.load(path), { file = "old.lua", line = 3, end_line = 7, line_ref = "old", issue = "Removed comment" })
    assert.is_true(store.save(path, items))
    buf, win = view.open(path, { file = "old.lua", line = 5, side = "old" })
    assert.matches("Removed comment", contents())
    assert.is_nil(contents():find("First comment", 1, true))
    press("f")
    assert.are.equal("fixed", store.load(path)[3].status)
    assert.matches("Removed comment", contents())
    press("<CR>")
    assert.is_true(vim.api.nvim_win_is_valid(win))
  end)
  it("cancels deletion and reloads after delayed confirmation", function()
    buf, win = view.open(path)
    local confirm
    require("locoreview.ui").prompt_confirm = function(_, cb) confirm = cb end
    press("d")
    confirm(false)
    assert.are.equal(2, #store.load(path))
    press("d")
    assert.is_true(store.save(path, add(store.load(path), { issue = "Arrived while confirming" })))
    confirm(true)
    local items = store.load(path)
    assert.are.equal(2, #items)
    assert.are.equal("Second comment", items[1].issue)
    assert.are.equal("Arrived while confirming", items[2].issue)
  end)
  it("retains a draft and its parent view on failed save", function()
    buf, win = view.open(path)
    press("e")
    local editor = vim.api.nvim_get_current_win()
    local original_save = store.save
    store.save = function() return nil, "disk full" end
    press("<C-s>")
    store.save = original_save
    assert.is_true(vim.api.nvim_win_is_valid(editor))
    assert.is_true(vim.api.nvim_win_is_valid(win))
    press("<C-c>")
    assert.are.equal(win, vim.api.nvim_get_current_win())
  end)
  it("refreshes manual changes while keeping the selected ID", function()
    buf, win = view.open(path)
    press("]c")
    local items = store.update(store.load(path), "RV-0002", { issue = "Updated elsewhere" })
    assert.is_true(store.save(path, items))
    press("R")
    assert.matches("Updated elsewhere", contents())
    press("f")
    assert.are.equal("fixed", store.load(path)[2].status)
  end)
end)
